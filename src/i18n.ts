/** Resolve "auto" from the browser language: German if the device prefers German, else English. */
export function resolveLang(setting: 'auto' | Lang, navLangs: readonly string[] = typeof navigator !== 'undefined' ? navigator.languages ?? [navigator.language] : []): Lang {
  if (setting !== 'auto') return setting;
  for (const l of navLangs) {
    const p = l.toLowerCase().slice(0, 2);
    if (p === 'de') return 'de';
    if (p === 'en') return 'en';
  }
  return 'en';
}
